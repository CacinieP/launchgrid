import AppKit
import XCTest
@testable import LaunchGrid

/// Uses a named pasteboard, isolated defaults and temporary history, never user data.
final class ClipboardControlTests: XCTestCase {
    private var fixture: Fixture!

    override func tearDown() {
        fixture?.dispose()
        fixture = nil
        super.tearDown()
    }

    func testDisabledUntilOptInSkipsPreexistingAndDisabledCopies() throws {
        fixture = try Fixture(enabled: false)
        fixture.write("before opt-in")
        fixture.store.start()
        fixture.store.captureCurrent()
        XCTAssertFalse(fixture.store.isCapturing)
        XCTAssertTrue(fixture.store.entries.isEmpty)

        fixture.preferences.clipboardEnabled = true
        fixture.store.captureCurrent()
        XCTAssertTrue(fixture.store.isCapturing)
        XCTAssertTrue(fixture.store.entries.isEmpty)
        fixture.copy("new consented copy")
        XCTAssertEqual(fixture.store.entries.map(\.text), ["new consented copy"])

        fixture.preferences.clipboardEnabled = false
        fixture.copy("copied while disabled")
        fixture.preferences.clipboardEnabled = true
        fixture.store.captureCurrent()
        XCTAssertEqual(fixture.store.entries.map(\.text), ["new consented copy"])
        fixture.copy("after enabling again")
        XCTAssertEqual(fixture.store.entries.first?.text, "after enabling again")
    }

    func testPauseAndResumeDoNotImportCopiesMadeWhilePaused() throws {
        fixture = try Fixture()
        fixture.store.start()
        fixture.copy("kept")
        fixture.store.setPaused(true)
        fixture.copy("private paused copy")
        XCTAssertFalse(fixture.store.isCapturing)
        XCTAssertEqual(fixture.store.entries.map(\.text), ["kept"])

        fixture.store.setPaused(false)
        fixture.store.captureCurrent()
        XCTAssertTrue(fixture.store.isCapturing)
        XCTAssertEqual(fixture.store.entries.map(\.text), ["kept"])
        fixture.copy("new after resume")
        XCTAssertEqual(fixture.store.entries.first?.text, "new after resume")
    }

    func testExcludedForegroundApplicationAndHiddenTypesAreSkipped() throws {
        fixture = try Fixture()
        fixture.preferences.ignoredClipboardBundleIDs = ["test.excluded"]
        fixture.sourceBundleID = "test.excluded"
        fixture.store.start()
        fixture.copy("excluded source")
        XCTAssertTrue(fixture.store.entries.isEmpty)

        fixture.sourceBundleID = "test.allowed"
        for name in ["ConcealedType", "AutoGeneratedType", "TransientType"] {
            let hidden = NSPasteboard.PasteboardType("org.nspasteboard.\(name)")
            fixture.pasteboard.clearContents()
            fixture.pasteboard.declareTypes([.string, hidden], owner: nil)
            fixture.pasteboard.setString("hidden \(name)", forType: .string)
            fixture.pasteboard.setData(Data(), forType: hidden)
            fixture.store.captureCurrent()
        }
        XCTAssertTrue(fixture.store.entries.isEmpty)
        fixture.copy("ordinary text")
        XCTAssertEqual(fixture.store.entries.first?.sourceBundleID, "test.allowed")
    }

    func testChangingExclusionsDoesNotImportPendingClipboard() throws {
        fixture = try Fixture()
        fixture.store.start()
        fixture.write("pending at privacy change")
        fixture.preferences.ignoredClipboardBundleIDs = ["test.other"]
        fixture.store.captureCurrent()
        XCTAssertTrue(fixture.store.entries.isEmpty)
        fixture.copy("fresh allowed copy")
        XCTAssertEqual(fixture.store.entries.map(\.text), ["fresh allowed copy"])
    }

    func testExclusionRemovesEarlierHistoryAndCannotBeOverwrittenByPendingSave() throws {
        fixture = try Fixture()
        fixture.store.start()
        fixture.copy("remove this source history")
        fixture.store.saveNow()
        fixture.preferences.ignoredClipboardBundleIDs = ["test.allowed"]
        fixture.store.flushPendingWrites()
        XCTAssertTrue(fixture.store.entries.isEmpty)
        XCTAssertTrue(try fixture.savedEntries().isEmpty)
    }

    func testLoadingHistoryHonorsPreviouslyConfiguredExclusions() throws {
        fixture = try Fixture()
        fixture.preferences.ignoredClipboardBundleIDs = ["legacy.excluded"]
        let excluded = ClipboardEntry(id: UUID(), text: "previously excluded",
                                      createdAt: fixture.date, sourceBundleID: "legacy.excluded",
                                      sourceName: "Excluded")
        let kept = ClipboardEntry(id: UUID(), text: "allowed", createdAt: fixture.date,
                                  sourceBundleID: "legacy.allowed", sourceName: "Allowed")
        try JSONEncoder().encode(LegacyPayload(version: 1, savedAt: fixture.date, entries: [excluded, kept]))
            .write(to: fixture.storeURL)
        fixture.store.start()
        XCTAssertEqual(fixture.store.entries, [kept])
        fixture.store.saveNow()
        fixture.store.flushPendingWrites()
        XCTAssertEqual(try fixture.savedEntries(), [kept])
    }

    func testClearWinsAgainstEarlierQueuedSavesAndSkipsCurrentClipboard() throws {
        fixture = try Fixture()
        fixture.store.start()
        for index in 0..<12 {
            fixture.copy("\(index):" + String(repeating: "x", count: 64_000))
            fixture.store.saveNow()
        }
        fixture.store.clearAll()
        fixture.store.captureCurrent()
        fixture.store.flushPendingWrites()
        XCTAssertTrue(fixture.store.entries.isEmpty)
        XCTAssertTrue(try fixture.savedEntries().isEmpty)
        let attributes = try FileManager.default.attributesOfItem(atPath: fixture.storeURL.path)
        XCTAssertEqual((attributes[.posixPermissions] as? NSNumber)?.intValue, 0o600)
    }

    func testRemoveWinsAgainstEarlierQueuedSave() throws {
        fixture = try Fixture()
        fixture.store.start()
        fixture.copy("delete me")
        let entry = try XCTUnwrap(fixture.store.entries.first)
        fixture.store.saveNow()
        fixture.store.remove(entry)
        fixture.store.flushPendingWrites()
        XCTAssertTrue(try fixture.savedEntries().isEmpty)
    }

    func testLoadsVersionOneHistoryOnceAndPrunesExpiredEntries() throws {
        fixture = try Fixture()
        let fresh = ClipboardEntry(id: UUID(), text: "legacy recent", createdAt: fixture.date,
                                   sourceBundleID: "legacy.source", sourceName: "Legacy")
        let expired = ClipboardEntry(id: UUID(), text: "legacy expired",
                                     createdAt: fixture.date.addingTimeInterval(-8 * 86_400),
                                     sourceBundleID: nil, sourceName: nil)
        let payload = LegacyPayload(version: 1, savedAt: fixture.date, entries: [expired, fresh])
        try JSONEncoder().encode(payload).write(to: fixture.storeURL)
        fixture.store.start()
        XCTAssertEqual(fixture.store.entries, [fresh])
        fixture.copy("current session")
        fixture.store.start()
        XCTAssertEqual(fixture.store.entries.map(\.text), ["current session", "legacy recent"])
        fixture.store.saveNow()
        fixture.store.flushPendingWrites()
        XCTAssertEqual(try fixture.savedEntries().count, 2)
    }

    func testStopThenStartSkipsCopiesMadeWhileStopped() throws {
        fixture = try Fixture()
        fixture.store.start()
        fixture.copy("kept")
        fixture.store.stop()
        fixture.copy("while stopped")
        fixture.store.start()
        fixture.store.captureCurrent()
        XCTAssertEqual(fixture.store.entries.map(\.text), ["kept"])
    }

    func testRetentionPrunesWhilePollingEvenIfClipboardDidNotChange() throws {
        fixture = try Fixture()
        fixture.store.start()
        fixture.copy("expires without another copy")
        fixture.date = fixture.date.addingTimeInterval(8 * 86_400)
        fixture.store.captureCurrent()
        XCTAssertTrue(fixture.store.entries.isEmpty)
        fixture.store.saveNow()
        fixture.store.flushPendingWrites()
        XCTAssertTrue(try fixture.savedEntries().isEmpty)
    }

    private struct LegacyPayload: Codable {
        var version: Int
        var savedAt: Date
        var entries: [ClipboardEntry]
    }

    private final class Fixture {
        let suiteName = "LaunchGrid.ClipboardTests.\(UUID().uuidString)"
        let defaults: UserDefaults
        let preferences: AppPreferences
        let pasteboard: NSPasteboard
        let directory: URL
        let storeURL: URL
        var date = Date(timeIntervalSince1970: 1_792_800_000)
        var sourceBundleID = "test.allowed"
        var store: ClipboardStore!

        init(enabled: Bool = true) throws {
            defaults = try XCTUnwrap(UserDefaults(suiteName: suiteName))
            preferences = AppPreferences(defaults: defaults, existingClipboardHistory: false)
            preferences.clipboardEnabled = enabled
            pasteboard = NSPasteboard(name: .init("LaunchGrid.ClipboardTests.\(UUID().uuidString)"))
            directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
            try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
            storeURL = directory.appendingPathComponent("clipboard.json")
            store = ClipboardStore(
                preferences: preferences, pasteboard: pasteboard, storeURL: storeURL,
                sourceProvider: { [weak self] in (self?.sourceBundleID, "Test Source") },
                now: { [weak self] in self?.date ?? Date(timeIntervalSince1970: 1_792_800_000) }
            )
        }

        func write(_ text: String) {
            pasteboard.clearContents()
            XCTAssertTrue(pasteboard.setString(text, forType: .string))
        }

        func copy(_ text: String) {
            write(text)
            store.captureCurrent()
        }

        func savedEntries() throws -> [ClipboardEntry] {
            try JSONDecoder().decode(LegacyPayload.self, from: Data(contentsOf: storeURL)).entries
        }

        func dispose() {
            store.stop()
            pasteboard.releaseGlobally()
            defaults.removePersistentDomain(forName: suiteName)
            try? FileManager.default.removeItem(at: directory)
        }
    }
}
